# Builds src/avatar_mocap.inc: CMU motion capture (mocap.cs.cmu.edu, "free to use for any purpose", via the 2010
# cgspeed BVH conversion in github.com/una-dinosauria/cmu-mocap) retargeted onto the body pack's two rigs (male:
# Body_mackenzie_indoor, female: Body_astrid; rig_local.json, dumped from tldcoop_bodies.bundle). Per clip and rig:
# frames at 30 fps of the posed bones' local rotations (int16 x4) and the hips' local position offset from rest (mm).
# Loops are cross-faded over their last 0.4 s into their start.
#   python3 tools/mocap/gen_clips.py <cmu-mocap checkout> [preview dir]
import sys, os, numpy as np
from rig import load, qnorm
from bvh import BVH
from retarget import retarget, POSED, humanize
from preview import strip
from gait import cycle

FPS = 30
# name, CMU take, start s, end s, loop, upper only (legs keep the gait), heading mode, keep the hips' height
CLIPS = [
    ('climb',  '13_33', 3.3, 8.3, True,  False, 'clip',   False),  # climb ladder: hand over hand (rope)
    ('kneel',  '77_06', 4.5, 7.5, True,  False, 'clip',   True),   # searching the ground: harvest, cook, rope
    ('fire',   '77_08', 1.5, 3.2, True,  False, 'clip',   True),   # investigating on the ground: lighting a fire
    ('chop',   '79_01', 1.3, 4.2, True,  False, 'clip',   True),   # chopping wood: breaking down
    ('search', '62_19', 3.3, 4.8, True,  True,  'clip',   True),   # opening a box: in a container
    ('work',   '79_34', 2.9, 5.3, True,  True,  'clip',   True),   # hands in front: workbench, reading
    ('sit',    '82_05', 3.0, 8.0, True,  False, 'clip',   True),   # sitting on the ground: ice fishing, a seat
    ('air',    '13_39', 1.50, 1.62, False, False, 'clip', False),  # mid-jump: in the air (held, not looped)
    ('fall',   '90_17', 3.0, 4.6, False, False, 'clip',   True),   # slipping and falling
    ('carry',  '111_36', 3.0, 9.0, True, True,  'smooth', True),   # walking, carrying: a big carry
    ('g_idle', '82_08', 0.5, 8.0, True, False, 'clip',   True),   # standing still (the gait's idle)
]
# The gait: one full stride each (left heel strike to the next; gait.py), its speed scales its playback. name, take,
# the window to find a steady stride in.
GAIT = [
    ('g_walk',  '07_01', 0.3, 2.4),   # walk
    ('g_run',   '35_17', 0.1, 1.2),   # run/jog
    ('g_creep', '77_14', 1.2, 3.4),   # careful creeping: walking crouched
]

# TLDCoop_DLC (08.11): retarget.humanize per clip: the arms out from the body (degrees) and how much the elbows bend
# (the hands on a rope or a load stay where they are)
HUMAN = {
    'climb': dict(abduct_deg=0), 'carry': dict(abduct_deg=0), 'search': dict(abduct_deg=5), 'work': dict(abduct_deg=5),
    'g_walk': dict(elbow_scale=0.55), 'g_run': dict(elbow_scale=0.75), 'g_creep': dict(elbow_scale=0.8),
}

def crossfade(frames, n):
    if n <= 0 or len(frames) <= 2 * n: return frames
    out = frames[:-n]
    for k in range(n):
        w = (k + 1) / (n + 1)
        a_local, a_hips = frames[len(frames) - n + k]
        b_local, b_hips = frames[k]
        blended = {}
        for name in a_local:
            qa, qb = a_local[name], b_local.get(name, a_local[name])
            if np.dot(qa, qb) < 0: qb = -qb
            blended[name] = qnorm(qa * (1 - w) + qb * w)
        out[len(out) - n + k] = (blended, a_hips * (1 - w) + b_hips * w) if False else out[len(out) - n + k]
    # simpler and exact: fade the clip's end into its start over n frames, then drop the faded copies of the start
    res = []
    L = len(frames) - n
    for i in range(L):
        local, hips = frames[i]
        if i >= L - n:
            k = i - (L - n); w = (k + 1) / (n + 1)
            local2, hips2 = frames[k]
            b = {}
            for name in local:
                qa, qb = local[name], local2[name]
                if np.dot(qa, qb) < 0: qb = -qb
                b[name] = qnorm(qa * (1 - w) + qb * w)
            res.append((b, hips * (1 - w) + hips2 * w))
        else:
            res.append((local, hips))
    return res

def pack(rig, frames):
    rest = rig.rest_pos[rig.index['Hips_jnt']]
    q = []; h = []
    for local, hips in frames:
        for bn in POSED:
            v = local.get(bn, rig.rest_rot[rig.index[bn]])
            if v[3] < 0: v = -v
            q += [int(round(c * 32767)) for c in v]
        d = (hips - rest) * 1000
        h += [int(round(c)) for c in d]
    return q, h

def main(cmu, preview=None):
    rigs = {'M': load(os.path.join(os.path.dirname(__file__), 'rig_local.json'), 'Body_mackenzie_indoor'),
            'F': load(os.path.join(os.path.dirname(__file__), 'rig_local.json'), 'Body_astrid')}
    lines = ['// Generated by tools/mocap/gen_clips.py from CMU motion capture (mocap.cs.cmu.edu; free for any use), retargeted',
             '// onto the body pack\'s rigs. Do not edit.', '',
             'constexpr int kMocapBones = %d;' % len(POSED),
             'const char* const kMocapBoneNames[kMocapBones] = {%s};' % ', '.join('"%s"' % b for b in POSED), '']
    table = []
    for name, take, t0, t1, loop, upper, heading, keep_y in CLIPS:
        b = BVH(os.path.join(cmu, 'data', '%03d' % int(take.split('_')[0]), take + '.bvh'))
        for rig_name, rig in rigs.items():
            frames = retarget(rig, b, t0, t1, fps=FPS, heading=heading, keep_y=keep_y)
            frames = humanize(rig, frames, **HUMAN.get(name, {}))
            if loop and len(frames) > 30: frames = crossfade(frames, int(0.4 * FPS))
            q, h = pack(rig, frames)
            var = 'kMocap_%s_%s' % (name, rig_name)
            lines.append('const int16_t %s_rot[%d] = {%s};' % (var, len(q), ','.join(map(str, q))))
            lines.append('const int16_t %s_hips[%d] = {%s};' % (var, len(h), ','.join(map(str, h))))
            table.append('    {"%s", \'%s\', %d, %s, %s, %s_rot, %s_hips, 0.0f},' % (name, rig_name, len(frames),
                         'true' if loop else 'false', 'true' if upper else 'false', var, var))
            if preview and rig_name == 'M':
                strip(rig, frames, os.path.join(preview, 'clip_%s.png' % name), n=10, title='%s (%s %.1f-%.1f s)' % (name, take, t0, t1))
            print(name, rig_name, len(frames), 'frames')
    for name, take, t0, t1 in GAIT:
        b = BVH(os.path.join(cmu, 'data', '%03d' % int(take.split('_')[0]), take + '.bvh'))
        for rig_name, rig in rigs.items():
            frames, speed, start, length, gap = cycle(rig, b, t0, t1, fps=FPS)
            frames = humanize(rig, frames, **HUMAN.get(name, {}))
            q, h = pack(rig, frames)
            var = 'kMocap_%s_%s' % (name, rig_name)
            lines.append('const int16_t %s_rot[%d] = {%s};' % (var, len(q), ','.join(map(str, q))))
            lines.append('const int16_t %s_hips[%d] = {%s};' % (var, len(h), ','.join(map(str, h))))
            table.append('    {"%s", \'%s\', %d, true, false, %s_rot, %s_hips, %.3ff},' % (name, rig_name, len(frames), var, var, speed))
            if preview and rig_name == 'M':
                strip(rig, frames, os.path.join(preview, 'clip_%s.png' % name), n=10, title='%s (%s, stride at %.2f s, %.2f m/s)' % (name, take, start, speed))
            print(name, rig_name, len(frames), 'frames, %.2f m/s, stride %.2f s at %.2f s, seam %.3f m' % (speed, length, start, gap))
    lines += ['', 'struct MocapClip {', '    const char* name;', '    char rig;          // M or F',
              '    int frames;        // at 30 fps', '    bool loop;', '    bool upper;        // from the spine up (the legs keep the gait)',
              '    const int16_t* rot;   // frames x kMocapBones x (x y z w) / 32767: local rotations',
              '    const int16_t* hips;  // frames x (x y z) mm: the hips\' local position minus its rest',
              '    float speed;       // a gait stride: its speed over the ground (m/s) at 1x; 0 not a gait', '};',
              'const MocapClip kMocapClips[] = {'] + table + ['};']
    open(os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'avatar_mocap.inc'), 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
