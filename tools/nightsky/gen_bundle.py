# Embeds third_party/better-night-sky/better-night-sky.bundle (Better Night Sky's moon, stars; MIT, see LICENSE there)
# into src/night_sky_bundle.inc.
import pathlib
root = pathlib.Path(__file__).resolve().parents[2]
data = (root / "third_party/better-night-sky/better-night-sky.bundle").read_bytes()
out = ["// Generated by tools/nightsky/gen_bundle.py from third_party/better-night-sky (MIT: WulfMarius, ds5678).",
       f"constexpr size_t kSkyBundleSize = {len(data)};",
       "alignas(16) const unsigned char kSkyBundle[] = {"]
for i in range(0, len(data), 32):
    out.append("".join(f"{b}," for b in data[i:i + 32]))
out.append("};")
(root / "src/night_sky_bundle.inc").write_text("\n".join(out) + "\n")
print(len(data), "bytes")
