#!/usr/bin/env python3
"""TLDCoop_DLC: our pictures (assets/pictures/*.png, already in the atlas' orientation and size; RGB, or RGBA whose alpha
blends it into TLD's own frame edge) -> src/pictures_data.inc.
Run from the repo root: python tools/pictures/gen_data.py"""
from PIL import Image

PICS = [
    # name, png, the atlas it goes into, the atlas size we build it at, x, y (top-left, top-down) in that size
    ("gm_a_6", "assets/pictures/gm_a_6.png", "OBJ_PictureFrame_GM_A", 1024, 430, 670),
    ("misc_1", "assets/pictures/misc_1.png", "OBJ_PictureMisc_01", 1024, 7, 12),  # top left (Karol, Oct 30)
    # the same picture on the TV screens (Karol, Nov 3): the old CRT and the house appliances' flat TV
    ("tv_old", "assets/pictures/tv_old.png", "OBJ_OldTelevision_A", 1024, 87, 117),
    ("tv_modern", "assets/pictures/tv_modern.png", "OBJ_InteriorHouseAppliances_A", 1024, 542, 707),
]

out = ["// Generated by tools/pictures/gen_data.py; do not edit.", ""]
for name, png, atlas, size, x, y in PICS:
    im = Image.open(png)
    im = im.convert("RGBA" if im.mode in ("RGBA", "LA") or "transparency" in im.info else "RGB")
    w, h = im.size
    data = im.tobytes()
    out.append(f"static const unsigned char k_{name}[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",")
    out.append("};")
    out.append("")
out.append("static const Picture kPictures[] = {")
for name, png, atlas, size, x, y in PICS:
    im = Image.open(png)
    w, h = im.size
    ch = 4 if im.mode in ("RGBA", "LA") else 3
    out.append(f'    {{"{atlas}", {size}, {x}, {y}, {w}, {h}, k_{name}, {ch}}},')
out.append("};")
open("src/pictures_data.inc", "w", newline="\n").write("\n".join(out) + "\n")
print("src/pictures_data.inc:", len(PICS), "picture(s)")
