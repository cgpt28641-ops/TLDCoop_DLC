# Embeds third_party/house-lights/hlbundle into src/house_lights_bundle.inc (the switch models of House Lights).
import pathlib
root = pathlib.Path(__file__).resolve().parents[2]
data = (root / "third_party/house-lights/hlbundle").read_bytes()
out = ["// Generated by tools/houselights/gen_bundle.py from third_party/house-lights/hlbundle (MIT, see NOTICE.txt).",
       f"constexpr size_t kBundleSize = {len(data)};",
       "alignas(16) const unsigned char kBundle[] = {"]
for i in range(0, len(data), 32):
    out.append("".join(f"{b}," for b in data[i:i + 32]))
out.append("};")
(root / "src/house_lights_bundle.inc").write_text("\n".join(out) + "\n")
print(len(data), "bytes")
