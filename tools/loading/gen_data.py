# Karol's start screens (assets/loading/loading_screen_1..3.jpg, in the order they show) -> src/loading_screen_data.inc
# (JPEG bytes, decoded in game by ImageConversion.LoadImage). Run from the repo root: python3 tools/loading/gen_data.py
from PIL import Image
out = ['// Generated by tools/loading/gen_data.py from assets/loading/loading_screen_*.jpg; do not edit.', '']
names = []
for i in (1, 2, 3):
    path = f'assets/loading/loading_screen_{i}.jpg'
    d = open(path, 'rb').read()
    w, h = Image.open(path).size
    out.append(f'const unsigned char kLoadingJpg{i}[{len(d)}] = {{')
    for k in range(0, len(d), 32):
        out.append('    ' + ','.join(str(x) for x in d[k:k + 32]) + ',')
    out.append('};')
    names.append(f'    {{kLoadingJpg{i}, sizeof(kLoadingJpg{i}), {w}, {h}}},')
out.append('struct StartPicture { const unsigned char* jpg; size_t size; int w, h; };')
out.append('const StartPicture kStartPictures[] = {')
out += names
out.append('};')
open('src/loading_screen_data.inc', 'w').write('\n'.join(out) + '\n')
