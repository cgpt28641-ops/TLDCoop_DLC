# Karol's loading screen (assets/loading/loading_screen.jpg) -> src/loading_screen_data.inc (JPEG bytes, decoded in game
# by ImageConversion.LoadImage). Run from the repo root: python3 tools/loading/gen_data.py
from PIL import Image
d = open('assets/loading/loading_screen.jpg', 'rb').read()
w, h = Image.open('assets/loading/loading_screen.jpg').size
out = ['// Generated by tools/loading/gen_data.py from assets/loading/loading_screen.jpg; do not edit.',
       f'constexpr int kLoadingW = {w}, kLoadingH = {h};', f'const unsigned char kLoadingJpg[{len(d)}] = {{']
for i in range(0, len(d), 32):
    out.append('    ' + ','.join(str(x) for x in d[i:i + 32]) + ',')
out.append('};')
open('src/loading_screen_data.inc', 'w').write('\n'.join(out) + '\n')
