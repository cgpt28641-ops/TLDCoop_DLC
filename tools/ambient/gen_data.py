#!/usr/bin/env python3
"""Turns AmbientLights' JSON (third_party/ambient-lights, MIT, Xpazeman / Thekillergreece) into src/ambient_data.inc:
plain C++ tables the mod compiles in, so players need no extra files and the mod no JSON parser.

Run from the repo root after changing the JSON:  python3 tools/ambient/gen_data.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "third_party", "ambient-lights")
OUT = os.path.join(ROOT, "src", "ambient_data.inc")
DIRS = ["north", "south", "east", "west"]
PERIODS = ["early_dawn", "dawn", "morning", "afternoon", "dusk", "after_dusk", "night", "default"]


def lenient(path):
    """The mod reads its files with TinyJSON, which takes trailing commas, a BOM and // comments."""
    raw = open(path, "rb").read()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:  # one file has a stray Latin-1 byte (inside a key the mod then ignores)
        text = raw.decode("latin-1")
    text = re.sub(r"^\s*//.*$", "", text, flags=re.M)
    # a few files miss the comma at a line's end ("position":"..." then "orientation"); TinyJSON reads on
    text = re.sub(r'(["\d\]}]|true|false)(\s*\n\s*")', r"\1,\2", text)
    text = re.sub(r"\}(\s*\n\s*\{)", r"},\1", text)
    text = re.sub(r",(\s*[}\]])", r"\1", text)
    return json.loads(text)


def f(x):
    s = repr(float(x))
    return s + ("f" if ("." in s or "e" in s) else ".0f")


def pair(v, default):
    v = v if v is not None else default
    return "{%s, %s}" % (f(v[0]), f(v[1]))


def main():
    out = ["// Generated by tools/ambient/gen_data.py from third_party/ambient-lights (AmbientLights by Xpazeman,",
           "// maintained by Thekillergreece; MIT licence, see third_party/ambient-lights/LICENSE). Do not edit.", ""]

    sets = lenient(os.path.join(DATA, "global_sets.json"))
    out.append("const PeriodSet kPeriods[] = {")
    for name in PERIODS:
        p = sets.get(name)
        if p is None:
            continue
        orients = []
        for d in DIRS:
            o = p.get("orientations", {}).get(d, {})
            hue = o.get("hue")
            orients.append("{%s, %s, %s}" % (pair(o.get("sun"), [0, 0]), pair(hue, [0, 0]), "true" if hue else "false"))
        out.append('    {"%s", {%s}, %s, %s, %s},' % (
            name, ", ".join(orients), pair(p.get("intensity"), [1, 1]), pair(p.get("range"), [10, 10]),
            pair(p.get("sun_strength"), [1, 1])))
    out.append("};")
    out.append("")

    weathers = lenient(os.path.join(DATA, "weather_sets.json"))
    out.append("const WeatherSet kWeathers[] = {")
    for name, w in weathers.items():
        out.append('    {"%s", %s, %s, %s, %s, %s, %s, %s},' % (
            name, f(w.get("sMod", 1)), f(w.get("vMod", 1)), f(w.get("rMod", 1)), f(w.get("gMod", 1)),
            f(w.get("bMod", 1)), f(w.get("intMod", 1)), f(w.get("rngMod", 1))))
    out.append("};")
    out.append("")

    scenes = []
    emitters = []
    for fn in sorted(os.listdir(DATA)):
        m = re.fullmatch(r"scene_(.+)\.json", fn)
        if not m:
            continue
        try:
            sc = lenient(os.path.join(DATA, fn))
        except Exception as e:  # a file the mod itself couldn't read either
            print("skipped %s: %s" % (fn, e), file=sys.stderr)
            continue
        first = len(emitters)
        for e in sc.get("emitters") or []:
            pos = [float(v) for v in str(e.get("position", "0,0,0")).strip("() ").split(",")]
            orient = str(e.get("orientation", "")).strip().lower()
            o = DIRS.index(orient) if orient in DIRS else 4  # 4: "default"
            emitters.append("    {%s, %s, %s, %d, %s, %s}," % (f(pos[0]), f(pos[1]), f(pos[2]), o,
                                                              f(e.get("size", 1)), f(e.get("cover", 0))))
        opt = sc.get("options") or {}
        scenes.append('    {"%s", %d, %d, %s, %s, %s},' % (
            m.group(1), first, len(emitters) - first, f(opt.get("intensity_multiplier", 1)),
            f(opt.get("range_multiplier", 1)), f(opt.get("ambient_intensity_multiplier", 1))))
    out.append("const Emitter kEmitters[] = {")
    out.extend(emitters)
    out.append("};")
    out.append("")
    out.append("const SceneLights kScenes[] = {")
    out.extend(scenes)
    out.append("};")
    open(OUT, "w", newline="\n").write("\n".join(out) + "\n")
    print("%s: %d periods, %d weathers, %d scenes, %d emitters" % (OUT, len(PERIODS), len(weathers), len(scenes),
                                                                  len(emitters)))


if __name__ == "__main__":
    main()
